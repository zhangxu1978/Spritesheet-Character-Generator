/** 逐词翻译：按空格/下划线/括号分词，逐个查字典，未命中保留原文。 */
export function wordTranslate(text: string): string {
  if (!text) return text;
  // 将单词与符号（空白、圆括号）分离，便于每个词单独查字典
  const tokens = text.split(/(\s+|\(|\))/);
  const translated = tokens
    .map((token) => {
      if (/^\s*$/.test(token) || /^[()]$/.test(token)) return token;
      const isUnderscoreSeparated = token.includes("_");
      if (isUnderscoreSeparated) {
        return token
          .split("_")
          .map((w) => wordDict[w.toLowerCase()] ?? w)
          .join("");
      }
      return wordDict[token.toLowerCase()] ?? token;
    })
    .join("");
  // 中文词之间不留空格（"浅 棕色" → "浅棕色"），混合文本保留分隔
  return translated.replace(
    /([\u4e00-\u9fff])\s+(?=[\u4e00-\u9fff])/g,
    "$1",
  );
}

/** 翻译类别名（目录名）。 */
export function translateCategory(name: string): string {
  if (!name) return name;
  const key = name.toLowerCase().replace(/-/g, "_");
  return categoryDict[key] ?? wordTranslate(name);
}

/** 翻译物品名（JSON name 字段）。 */
export function translateItem(name: string): string {
  if (!name) return name;
  const key = name.toLowerCase().replace(/-/g, "_");
  return exactItemDict[key] ?? wordTranslate(name);
}

/** 翻译变体名（variant，形如 "light_brown" 或 "light brown"）。 */
export function translateVariant(name: string): string {
  if (!name) return name;
  const key = name.toLowerCase().replace(/-/g, "_");
  return exactItemDict[key] ?? wordTranslate(name);
}

/** 翻译调色板名（palette）。 */
export function translatePalette(name: string): string {
  if (!name) return name;
  return wordTranslate(name);
}

/** 翻译身体类型。 */
export function translateBodyType(name: string): string {
  if (!name) return name;
  return bodyTypeDict[name.toLowerCase()] ?? name;
}

/** 翻译动画显示名（label）。 */
export function translateAnimationLabel(label: string): string {
  if (!label) return label;
  return wordTranslate(label.replace(/-/g, " "));
}

/** 通用翻译入口：先精确匹配，再逐词翻译。用于搜索匹配等场景。 */
export function translateText(text: string): string {
  if (!text) return text;
  const key = text.toLowerCase().replace(/-/g, "_");
  return exactItemDict[key] ?? wordTranslate(text);
}
